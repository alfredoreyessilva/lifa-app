// `children` es lo que la fila lleva al final y no es un contacto: "Compartir esta
// liga", que así no gasta un renglón propio.
export default function LeagueContacts({ league, children }) {
  const contactos = contactosDeLiga(league);

  return (
    <ul className="lp-contact" aria-label={`Contacto y redes de ${league.name}`}>
      {contactos.map(({ key, label, href }) => (
        <li key={key}>
          <a href={href} target="_blank" rel="noopener noreferrer" className="btn btn-outline btn-sm">
            {ICONOS[key]}
            {label}
          </a>
        </li>
      ))}
      <li>{children}</li>
    </ul>
  );
}
